#!/usr/bin/env python3
"""Generate .project/PARITY_INVENTORY.md from the original PrePoMax sources.

The inventory lists every original user command, form and model/mesh feature
class. Status per item is kept in .project/parity-status.json and merged on
regeneration, so rerunning after an upstream sync adds new items without
losing recorded progress.

Status letters (cumulative):
  A  original domain class builds in the whole cross-platform libraries
  B  reachable through the original Controller/Commands without WinForms
  C  available in the cross-platform UI
  V  verified against the original Windows application
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / ".project" / "PARITY_INVENTORY.md"
STATUS = ROOT / ".project" / "parity-status.json"

ABSTRACT_OR_HELPER = re.compile(r"(Enum|Data|Base|Collection|Interface|Legacy|Portable|Compatibility)$")


def classes(folder: Path, pattern: str = "*.cs") -> list[str]:
    names = set()
    for f in folder.rglob(pattern):
        if "_Compatibility" in f.parts or f.name.endswith(".Designer.cs"):
            continue
        stem = f.name.split(".")[0]
        if ABSTRACT_OR_HELPER.search(stem) or stem.startswith("I") and stem[1:2].isupper():
            continue
        names.add(stem)
    return sorted(names)


def grouped(root: Path, prefix: str) -> dict[str, list[str]]:
    groups: dict[str, list[str]] = {}
    for f in sorted(root.rglob(f"{prefix}*.cs")):
        if f.name.endswith(".Designer.cs") or "_Compatibility" in f.parts:
            continue
        rel = f.relative_to(root)
        group = re.sub(r"^\d+_", "", rel.parts[0]) if len(rel.parts) > 1 else "General"
        groups.setdefault(group, []).append(f.name.split(".")[0])
    return {k: sorted(set(v)) for k, v in groups.items()}


def sections() -> list[tuple[str, dict[str, list[str]]]]:
    model = ROOT / "CaeModel"
    mesh = ROOT / "CaeMesh"
    features = {
        "Steps": [n for n in classes(model / "Steps", "*Step.cs") if n not in ("Step", "InitialStep")],
        "Materials": [n for n in classes(model / "Materials") if n not in ("Material", "MaterialProperty")],
        "Sections": [n for n in classes(model / "Sections") if n != "Section"],
        "Constraints": [n for n in classes(model / "Constraints") if n != "Constraint"],
        "Contact": classes(model / "Contact"),
        "Amplitudes": classes(model / "Amplitudes"),
        "Distributions": classes(model / "Distributions"),
        "Initial conditions": classes(model / "InitialConditions"),
        "Boundary conditions": [n for n in classes(model / "Steps" / "BoundaryConditions") if n != "BoundaryCondition"],
        "Loads": [n for n in classes(model / "Steps" / "Loads") if n != "Load"],
        "Defined fields": classes(model / "Steps" / "DefinedFields"),
        "Field outputs": classes(model / "Steps" / "FieldOutputs"),
        "History outputs": classes(model / "Steps" / "HistoryOutputs"),
        "Step controls / damping": classes(model / "Steps" / "Controls") + classes(model / "Steps" / "Damping"),
        "Elements": classes(mesh / "Elements"),
        "Meshers": sorted(p.name for p in (mesh / "Meshing").iterdir() if p.is_dir() and p.name not in ("Base", "IntervalAssignment")),
    }
    return [
        ("Model and mesh features", {k: v for k, v in features.items() if v}),
        ("Commands", grouped(ROOT / "PrePoMax" / "Commands", "C")),
        ("Forms", grouped(ROOT / "PrePoMax" / "Forms", "Frm")),
    ]


def main() -> None:
    status: dict[str, str] = json.loads(STATUS.read_text()) if STATUS.exists() else {}
    lines = [
        "# Parity inventory (generated)",
        "",
        "Generated by `.project/scripts/parity-inventory.py` from the original sources;",
        "edit status in `.project/parity-status.json`, then regenerate. Status letters",
        "are cumulative: **A** builds in the whole cross-platform domain libraries,",
        "**B** reachable through the original Controller/Commands without WinForms,",
        "**C** in the cross-platform UI, **V** verified against the original app.",
        "`-` = not yet. This is the progress measure (D062).",
        "",
    ]
    summary = []
    body = []
    for title, groups in sections():
        body += [f"## {title}", ""]
        total = 0
        counts = {k: 0 for k in "ABCV"}
        for group, names in groups.items():
            body += [f"### {group}", "", "| Item | Status |", "|---|---|"]
            for name in names:
                key = f"{title}/{group}/{name}"
                st = status.setdefault(key, "-")
                body.append(f"| {name} | {st} |")
                total += 1
                for k in counts:
                    counts[k] += k in st
            body.append("")
        summary.append(f"| {title} | {total} | " + " | ".join(str(counts[k]) for k in "ABCV") + " |")
    lines += ["| Area | Items | A | B | C | V |", "|---|---|---|---|---|---|", *summary, "", *body]
    OUT.write_text("\n".join(lines))
    STATUS.write_text(json.dumps(dict(sorted(status.items())), indent=1) + "\n")


if __name__ == "__main__":
    main()
