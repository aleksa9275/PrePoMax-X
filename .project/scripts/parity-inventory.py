#!/usr/bin/env python3
"""Generate .project/PARITY_INVENTORY.md from the original PrePoMax sources.

The inventory lists original command/form files and selected concrete model/mesh
classes and mesher folders. Status per item is kept in .project/parity-status.json and merged on
regeneration, so rerunning after an upstream sync adds new items without
losing recorded progress.

Status letters (cumulative):
  A  original class builds in the whole cross-platform domain/Controller libraries
  B  reachable through the original Controller/Commands without WinForms
  C  available in the cross-platform UI
  V  verified against the original Windows application
"""
from __future__ import annotations

import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / ".project" / "PARITY_INVENTORY.md"
STATUS = ROOT / ".project" / "parity-status.json"

ABSTRACT_OR_HELPER = re.compile(r"(Enum|Data|Base|Collection|Interface|Legacy|Portable|Compatibility)$")
COMPILED = {
    (ROOT / assembly / item.get("Include").replace("\\", "/")).resolve()
    for assembly in ("CaeModel", "CaeMesh")
    for item in ET.parse(ROOT / assembly / (assembly + ".csproj")).getroot().iter()
    if item.tag.endswith("}Compile") and item.get("Include")
}


def classes(folder: Path, pattern: str = "*.cs") -> list[str]:
    names = set()
    for f in folder.rglob(pattern):
        if "_Compatibility" in f.parts or f.name.endswith(".Designer.cs") or f.resolve() not in COMPILED:
            continue
        text = re.sub(r"//[^\n]*|/\*.*?\*/", "", f.read_text(), flags=re.S)
        declaration = re.search(r"\b((?:(?:abstract|sealed|partial)\s+)*)class\s+(\w+)", text)
        if not declaration or "abstract" in declaration[1].split():
            continue
        stem = declaration[2]
        if ABSTRACT_OR_HELPER.search(stem) or stem.startswith("I") and stem[1:2].isupper():
            continue
        names.add(stem)
    return sorted(names)


def grouped(root: Path, prefix: str) -> dict[str, list[str]]:
    groups: dict[str, list[str]] = {}
    for f in sorted(root.rglob(f"{prefix}*.cs")):
        if f.name.endswith(".Designer.cs") or "_Compatibility" in f.parts:
            continue
        rel = f.relative_to(root)
        group = re.sub(r"^\d+_", "", rel.parts[0]) if len(rel.parts) > 1 else "General"
        groups.setdefault(group, []).append(f.name.split(".")[0])
    return {k: sorted(set(v)) for k, v in groups.items()}


def sections() -> list[tuple[str, dict[str, list[str]]]]:
    model = ROOT / "CaeModel"
    mesh = ROOT / "CaeMesh"
    features = {
        "Steps": [n for n in classes(model / "Steps", "*Step.cs") if n not in ("Step", "InitialStep")],
        "Materials": [n for n in classes(model / "Materials") if n not in ("Material", "MaterialProperty")],
        "Sections": [n for n in classes(model / "Sections") if n != "Section"],
        "Constraints": [n for n in classes(model / "Constraints") if n != "Constraint"],
        "Contact": classes(model / "Contact"),
        "Amplitudes": classes(model / "Amplitudes"),
        "Distributions": classes(model / "Distributions"),
        "Initial conditions": classes(model / "InitialConditions"),
        "Boundary conditions": [n for n in classes(model / "Steps" / "BoundaryConditions") if n != "BoundaryCondition"],
        "Loads": [n for n in classes(model / "Steps" / "Loads") if n != "Load"],
        "Defined fields": classes(model / "Steps" / "DefinedFields"),
        "Field outputs": classes(model / "Steps" / "FieldOutputs"),
        "History outputs": classes(model / "Steps" / "HistoryOutputs"),
        "Step controls / damping": classes(model / "Steps" / "Controls") + classes(model / "Steps" / "Damping"),
        "Elements": classes(mesh / "Elements"),
        "Meshers": sorted(p.name for p in (mesh / "Meshing").iterdir() if p.is_dir() and p.name not in ("Base", "IntervalAssignment")),
    }
    return [
        ("Model and mesh features", {k: v for k, v in features.items() if v}),
        ("Commands", grouped(ROOT / "PrePoMax" / "Commands", "C")),
        ("Forms", grouped(ROOT / "PrePoMax" / "Forms", "Frm")),
    ]


def main() -> None:
    status: dict[str, str] = json.loads(STATUS.read_text()) if STATUS.exists() else {}
    lines = [
        "# Parity inventory (generated)",
        "",
        "Generated by `.project/scripts/parity-inventory.py` from the original sources;",
        "edit status in `.project/parity-status.json`, then regenerate. Status letters",
        "are cumulative: **A** builds in the whole cross-platform domain/Controller libraries,",
        "**B** reachable through the original Controller/Commands without WinForms,",
        "**C** in the cross-platform UI, **V** verified against the original app.",
        "`-` = not yet. A is compilation evidence only; it does not prove runtime portability.",
        "",
        "This is a selected source inventory, not a whole-product percentage. It lists",
        "concrete classes compiled by the original model/mesh projects and mesher folders;",
        "some entries are data/helper classes. Model/mesh abstract bases and unused files",
        "are excluded; Commands lists source entries, including its base. Results tools,",
        "utilities, automation, dependencies and installers need separate acceptance. B records",
        "structural reachability, not execution of every feature. V requires full item coverage.",
        "Upstream 3.0.1 removed the dormant Q-Morph wrapper. B coverage is documented in the Phase B report;",
        "bounded original-app interoperability does not mark whole feature families V.",
        "C1 connects Open/Save/ReplaceMaterial through the UI; existing material editing",
        "and the native viewport foundation are detailed in [the C1 report](reports/phase-c1-ui-foundation.md).",
        "C2 adds core model authoring through original property views/factories/apply rules;",
        "C marks UI availability, not exhaustive execution of each item or complete form/control parity.",
        "C3 connects geometry editing, all original mesh setup types, native meshing and mesh editing.",
        "C4 connects original jobs, results authoring/display, viewport symbols/plots/sections/patterns/animation/captures.",
        "C5 adds original application/settings/library/history/keyword/automation/query/advisor/plotting tools and result-component actions.",
        "C6 rebuilds the original FrmMain main menu (16 menus, 313 release-visible items) from FrmMain; see [C6](reports/phase-c6-main-window.md).",
        "C7 adds the original FrmMain tool strips and the three-tab ModelTree with its context-menu rules; see [C7](reports/phase-c7-toolbars-tree.md).",
        "C8 completes the ModelTree (rename, drag and drop, groups, cells, keys, mouse over) and adds executed UI evidence for",
        "the solid/shell element classes, mass/spring/gap elements, InvertedElements, MassSection and Damping; beam element",
        "classes stay AB (created only from CAD edges and beam results); see [C8](reports/phase-c8-tree-elements.md).",
        "Since M1 the C evidence of the 3D view runs on the original vtkControl (upstream vtkNative, VTK 9.7.1) on macOS and",
        "Linux ARM64, not on a reimplemented renderer; see [M1](reports/phase-m1-original-vtkcontrol.md).",
        "Commands marked 'compatibility only' are never constructed by the original UI (old-history types or controller-inserted).",
        "See [C2](reports/phase-c2-model-authoring.md), [C3](reports/phase-c3-geometry-meshing.md), [C4](reports/phase-c4-jobs-results.md) and [C5](reports/phase-c5-application-tools.md).",
        "The [C5 source audit](reports/phase-c5-ui-audit.json) inventories all 72 forms and their designer fields/events; it does not accept full forms.",
        "Partial form reuse does not mark a complete form C; backend/four-target execution remains separate.",
        "C9 compiles 39 original form classes whole (FrmProperties family, FrmNewModel, FrmSelectItemSet) against a headless",
        "WinForms control model and hosts them with the original FrmMain members; forms reachable from the UI with executed",
        "evidence are ABC (A: the original class builds, B: it runs without WinForms, C: in the UI); see",
        "[C9](reports/phase-c9-original-forms.md).",
        "",
    ]
    summary = []
    body = []
    active_status = {}
    for title, groups in sections():
        body += [f"## {title}", ""]
        total = 0
        counts = {k: 0 for k in "ABCV"}
        for group, names in groups.items():
            body += [f"### {group}", "", "| Item | Status |", "|---|---|"]
            for name in names:
                key = f"{title}/{group}/{name}"
                st = status.setdefault(key, "-")
                active_status[key] = st
                body.append(f"| {name} | {st} |")
                total += 1
                for k in counts:
                    counts[k] += k in st
            body.append("")
        summary.append(f"| {title} | {total} | " + " | ".join(str(counts[k]) for k in "ABCV") + " |")
    lines += ["| Area | Items | A | B | C | V |", "|---|---|---|---|---|---|", *summary, "", *body]
    OUT.write_text("\n".join(lines))
    STATUS.write_text(json.dumps(dict(sorted(active_status.items())), indent=1) + "\n")


if __name__ == "__main__":
    main()
