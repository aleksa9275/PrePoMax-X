#!/usr/bin/env python3
"""Generate X/Domain/<Assembly>/Sources.g.props from the original .csproj files.

The original net48 projects stay the single source of truth for which files
belong to each assembly; domain-sources.json lists the few reviewed portable
deviations. Run with --check to verify the generated files are current (for
example after an upstream sync).
"""
from __future__ import annotations

import argparse
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
NS = {"m": "http://schemas.microsoft.com/developer/msbuild/2003"}


def items(project: Path, kind: str) -> list[str]:
    tree = ET.parse(project)
    return [e.get("Include").replace("\\", "/") for e in tree.getroot().iterfind(f".//m:{kind}", NS)]


def render(name: str, cfg: dict) -> str:
    project = ROOT / cfg["project"]
    base = project.parent.relative_to(ROOT).as_posix()
    original = items(project, "Compile")
    if "include" in cfg:
        # Subset assembly (e.g. the data classes of the rendering assembly): only the listed files.
        missing = [c for c in cfg["include"] if c not in original]
        if missing:
            raise SystemExit(f"{name}: included files not in original project: {missing}")
        original = list(cfg["include"])
    compile_items = [c for c in original if c not in cfg["exclude"]]
    missing = [c for c in cfg["exclude"] if c not in original]
    if missing:
        raise SystemExit(f"{name}: excluded files not in original project: {missing}")
    lines = [
        "<Project>",
        f"  <!-- Generated by X/Domain/domain_sources.py from {cfg['project']}; do not edit. -->",
        "  <ItemGroup>",
    ]
    for c in compile_items:
        lines.append(f'    <Compile Include="$(RepositoryRoot){base}/{c}" Link="{c}" />')
    for path, reason in cfg["add"].items():
        if not (ROOT / path).exists():
            raise SystemExit(f"{name}: added file missing: {path}")
        lines.append(f'    <Compile Include="$(RepositoryRoot){path}" Link="X/{Path(path).name}" /> <!-- {reason} -->')
    for r in ([] if "include" in cfg else items(project, "EmbeddedResource")):
        if r.endswith(".resx"):
            continue  # WinForms designer resources belong to the UI layer (Phase C)
        lines.append(f'    <EmbeddedResource Include="$(RepositoryRoot){base}/{r}" Link="{r}" />')
    lines += ["  </ItemGroup>", "</Project>", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()
    cfg = json.loads((HERE / "domain-sources.json").read_text())
    stale = []
    for name, a in cfg["assemblies"].items():
        out = HERE / name / "Sources.g.props"
        text = render(name, a)
        if args.check:
            if not out.exists() or out.read_text() != text:
                stale.append(str(out.relative_to(ROOT)))
        else:
            out.parent.mkdir(exist_ok=True)
            out.write_text(text)
    if stale:
        print("stale generated source lists:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
