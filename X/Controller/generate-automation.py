#!/usr/bin/env python3
"""Retain original automation server, replacing only OS permission boundaries."""
import argparse,hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
def replace_method(text,name,body):
 start=text.index('{',text.index(name+'('));depth=1;end=start+1
 while depth:
  if text[end]=='{':depth+=1
  elif text[end]=='}':depth-=1
  end+=1
 return text[:start]+'{\n'+body+'\n        }'+text[end:]
for name in ['RpcServer','RpcSessionInfoWriter']:
 source=ROOT/'PrePoMax/Rpc'/f'{name}.cs';s=source.read_text(encoding='utf-8-sig')
 if name=='RpcServer':
  # Search the declaration, not its invocation.
  start=s.index('private NamedPipeServerStream CreateStream()')
  s=s[:start]+replace_method(s[start:],'CreateStream','''            // .NET enforces the current-user boundary on both Unix sockets and Windows pipes.
            return new NamedPipeServerStream(_pipeName, PipeDirection.InOut, MaximumConnections,
                PipeTransmissionMode.Byte, PipeOptions.Asynchronous | PipeOptions.CurrentUserOnly, 4096, 4096);''')
 else:
  start=s.index('private static void EnsureSessionsDirectory()')
  original=s[start:s.index('private static string GetFileName()',start)]
  body=original[original.index('{')+1:original.rfind('}')]
  body=body.replace('Directory.CreateDirectory(directory, security);','new DirectoryInfo(directory).Create(security);').replace('Directory.GetAccessControl(directory, AccessControlSections.Access)','new DirectoryInfo(directory).GetAccessControl(AccessControlSections.Access)').replace('Directory.SetAccessControl(directory, existing);','new DirectoryInfo(directory).SetAccessControl(existing);')
  new='''            if (!OperatingSystem.IsWindows())
            {
                string path=GetSessionsDirectory();
                if (Directory.Exists(path) && new DirectoryInfo(path).LinkTarget!=null)
                    throw new IOException("The automation session directory may not be a symbolic link.");
                Directory.CreateDirectory(path, UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute);
                File.SetUnixFileMode(path, UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute);
                return;
            }
'''+body
  s=s[:start]+replace_method(s[start:],'EnsureSessionsDirectory',new)
  # User-private directory makes the token file private at creation; tighten its mode as well.
  s=s.replace('public const string ProtocolVersion', 'public static string NativeSessionsDirectory {get;set;}\n        public const string ProtocolVersion').replace('string root = Environment.GetFolderPath', 'if(NativeSessionsDirectory!=null){if(!Path.IsPathFullyQualified(NativeSessionsDirectory))throw new ArgumentException("Session directory must be absolute.");return NativeSessionsDirectory;}\n            string root = Environment.GetFolderPath')
  s=s.replace('writer.SaveToFile(fileName);','writer.SaveToFile(fileName);\n            if(!OperatingSystem.IsWindows())File.SetUnixFileMode(fileName,UnixFileMode.UserRead|UnixFileMode.UserWrite);')
 s='// Generated by X/Controller/generate-automation.py. Original SHA256 '+hashlib.sha256(source.read_bytes()).hexdigest()+'\n'+s
 s='\n'.join(line.rstrip() for line in s.splitlines()).rstrip()+'\n'
 out=ROOT/'X/Controller/Host'/f'{name}.Portable.g.cs'
 if a.check:
  if not out.exists() or out.read_text()!=s:raise SystemExit('Stale automation source: '+name)
 else:out.write_text(s)

source=ROOT/'PrePoMax/Forms/00_Common/FileExporter/ViewExportFileProperties.cs'
s=source.read_text(encoding='utf-8-sig');start=s.index('    [Serializable]')
s='// Generated; original property view SHA256 '+hashlib.sha256(source.read_bytes()).hexdigest()+'\nusing System;using System.ComponentModel;using System.Drawing.Design;using CaeGlobals;using DynamicTypeDescriptor;\nnamespace PrePoMax {\npublic sealed class CreateFileNameEditor : UITypeEditor {public static string FileName;public static string Filter;}\n'+s[start:]
s='\n'.join(line.rstrip() for line in s.splitlines()).rstrip()+'\n'
out=ROOT/'X/Controller/Host/ViewExportFileProperties.Portable.g.cs'
if a.check:
 if not out.exists() or out.read_text()!=s:raise SystemExit('Export property view is stale.')
else:out.write_text(s)
