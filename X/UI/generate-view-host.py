#!/usr/bin/env python3
"""Compile the view half of the original FrmMain (M1): its IControllerHost members that drive vtkControl.

The original FrmMain forwards about 130 controller calls to its vtkControl (_vtk) through InvokeIfRequired. Their
bodies are copied unchanged into X/UI/Workbench/OriginalViewHost.g.cs, a partial class that owns the original
vtkControl of the Qt viewport; OriginalViewHost.cs supplies the InvokeIfRequired marshalling and the few members
whose original bodies also change FrmMain's own controls (listed in MIXED, view part only). The output records the
source paths and SHA256; --check fails when an original changed or the output was edited.
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = HERE / 'Workbench/OriginalViewHost.g.cs'
SOURCES = ['PrePoMax/Forms/FrmMain.cs', 'PrePoMax/Forms/FrmMain.ControllerHost.cs', 'PrePoMax/Forms/FrmMain.Plotting.cs',
           'PrePoMax/IControllerHost.cs']
# Members whose original bodies change FrmMain's own controls as well as the view: OriginalViewHost.cs keeps
# their view statements (the toolkit mirrors the rest).
MIXED = {
    'ClearControls': 'clears the tree, the output and the result controls of FrmMain as well',
    'Clear3D': 'commits the viewport text editor (FrmMain control) first',
    'SetAnimationFrame': 'commits the viewport text editor (FrmMain control) first',
    'SetMenuAndToolStripVisibility': 'enables FrmMain menus and tool strips; only _vtk.Visible is view state',
    'SetCurrentEdgesVisibilities': 'checks the FrmMain edge buttons and updates the highlight of FrmMain forms',
}
# Not view members although their bodies mention _vtk: the toolkit keeps handling them
EXCLUDED = {
    'SelectBaseParts': 'selects parts in the FrmMain model tree and its forms (Controller_ActorsPicked handler)',
}
# Copied whole besides the controller members: the marshalling helpers the bodies call
HELPERS = ['InvokeIfRequired']


def sha(path):
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def host_members():
    text = re.sub(r'//.*', '', (ROOT / 'PrePoMax/IControllerHost.cs').read_text(encoding='utf-8-sig'))
    return set(re.findall(r'\b(\w+)\s*\(', text))


def render(extractor):
    forms = json.loads(subprocess.check_output(['dotnet', str(extractor), str(ROOT)], text=True))
    methods = [m for f in forms if f['name'] == 'FrmMain' for m in f['methods']]
    names = host_members()
    chosen = [m for m in methods if (m['name'] in names and m['body'] and '_vtk' in m['body'] and m['name'] not in MIXED and m['name'] not in EXCLUDED)
              or m['name'] in HELPERS]
    missing = [n for n in MIXED if not any(m['name'] == n for m in methods)]
    if missing:
        raise SystemExit(f'MIXED members no longer in FrmMain: {missing}')
    lines = ['// <auto-generated> by X/UI/generate-view-host.py from the original FrmMain; do not edit.',
             '// Sources (SHA256):']
    lines += [f'//   {s} {sha(s)}' for s in SOURCES]
    lines += ['// Not copied (toolkit): ' + ', '.join(f'{k} ({v})' for k, v in EXCLUDED.items())]
    lines += ['// View part only, in OriginalViewHost.cs: ' + ', '.join(f'{k} ({v})' for k, v in MIXED.items()),
              '#pragma warning disable', 'using System;', 'using System.Collections.Generic;', 'using System.Drawing;',
              'using System.Linq;', 'using System.Windows.Forms;', 'using CaeGlobals;', 'using CaeMesh;',
              'using CaeModel;', 'using CaeResults;', 'using vtkControl;', '', 'namespace PrePoMax', '{',
              '    public sealed partial class OriginalViewHost', '    {']
    for m in sorted(chosen, key=lambda m: (m['name'], m['code'])):
        code = m['code'].replace('\r\n', '\n')
        # Every member is public here: the dispatcher binds the controller's calls by name
        code = re.sub(r'^(private|protected|internal)\s+', 'public ', code)
        lines += ['        ' + code, '']
    lines += ['    }', '}', '']
    return '\n'.join(lines), len(chosen)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    p.add_argument('--extractor', type=Path, default=HERE / 'FormSourceGen/bin/Release/net10.0/FormSourceGen.dll')
    a = p.parse_args()
    text, count = render(a.extractor)
    if a.check:
        if not OUT.is_file() or OUT.read_text() != text:
            print(f'{OUT.relative_to(ROOT)} is stale; run X/UI/generate-view-host.py', file=sys.stderr)
            return 1
        print(json.dumps({'viewHostMembers': count, 'mixed': sorted(MIXED)}))
        return 0
    OUT.write_text(text)
    print(json.dumps({'written': str(OUT.relative_to(ROOT)), 'viewHostMembers': count}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
