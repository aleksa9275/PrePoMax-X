#!/usr/bin/env python3
"""A Linux desktop session for PrePoMax-X in Podman (M3-1b): the runtime image (Containerfile.run: Ubuntu 24.04,
Xvfb, Mesa software OpenGL, Openbox, x11vnc) with a package mounted read-only and a work folder read-write, both at
their host paths. The repository is not mounted, so the application under test can read nothing from it.

  python3 X/Build/Linux/session.py start --package <PrePoMax-X folder> --work <dir> [--vnc] [--size 1920x1080]
  python3 X/Build/Linux/session.py launcher --work <dir>   # writes <dir>/launch.sh: runs the package in the session
  python3 X/Build/Linux/session.py run [-- ARGS]   # starts PrePoMax-X in the session for a person (VNC), detached
  python3 X/Build/Linux/session.py stop

launch.sh forwards the PREPOMAXX_* variables and runs the package's launcher inside the session with its own hard
timeout (PREPOMAXX_SESSION_TIMEOUT, default 470 s), so run_probe_areas.py --launcher <dir>/launch.sh drives it as
it drives the macOS bundle. --vnc publishes the display on localhost:5901 only (macOS Screen Sharing:
vnc://localhost:5901, password --vnc-password, default "prepomax"; Screen Sharing does not take password-less servers).
"""
import argparse
import subprocess
import time
from pathlib import Path

IMAGE = 'prepomax-x-run:24.04'
NAME = 'prepomax-x-session'

SESSION = r'''
Xvfb :1 -screen 0 {size}x24 -nolisten tcp >/tmp/xvfb.log 2>&1 &
for i in $(seq 50); do [ -e /tmp/.X11-unix/X1 ] && break; sleep 0.1; done
DISPLAY=:1 openbox >/tmp/openbox.log 2>&1 &
{vnc}
exec sleep infinity
'''


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('action', choices=('start', 'launcher', 'run', 'stop'))
    p.add_argument('args', nargs='*')
    p.add_argument('--vnc-password', default='prepomax')
    p.add_argument('--package', type=Path)
    p.add_argument('--work', type=Path)
    p.add_argument('--vnc', action='store_true')
    p.add_argument('--size', default='1920x1080')
    a = p.parse_args()
    if a.action == 'stop':
        subprocess.run(['podman', 'rm', '-f', NAME], capture_output=True)
        return
    if a.action == 'run':
        package = Path((a.work.resolve() / 'package').read_text())
        subprocess.run(['podman', 'exec', '-d', '-w', '/', NAME, 'sh', '-c',
                        f'exec "{package}/PrePoMax-X" "$@" >>"{a.work.resolve()}/run.log" 2>&1', 'run', *a.args], check=True)
        print('PrePoMax-X started in the session; log', a.work.resolve() / 'run.log')
        return
    work = a.work.resolve()
    work.mkdir(parents=True, exist_ok=True)
    if a.action == 'start':
        package = a.package.resolve()
        subprocess.run(['podman', 'rm', '-f', NAME], capture_output=True)
        vnc = (f'x11vnc -storepasswd {a.vnc_password} /tmp/vncpass >/dev/null 2>&1; '
               'x11vnc -display :1 -forever -shared -rfbauth /tmp/vncpass -rfbport 5901 >/tmp/x11vnc.log 2>&1 &') if a.vnc else ''
        command = ['podman', 'run', '-d', '--name', NAME, '--shm-size', '1g',
                   '-v', f'{package}:{package}:ro', '-v', f'{work}:{work}', '-e', 'DISPLAY=:1',
                   '-e', f'PREPOMAXX_DATA={work}/data', '-e', f'HOME=/home/user']
        if a.vnc:
            command += ['-p', '127.0.0.1:5901:5901']
        subprocess.run([*command, IMAGE, 'sh', '-c', SESSION.format(size=a.size, vnc=vnc)], check=True)
        for _ in range(50):
            if subprocess.run(['podman', 'exec', NAME, 'test', '-e', '/tmp/.X11-unix/X1'], capture_output=True).returncode == 0:
                break
            time.sleep(0.2)
        (work / 'package').write_text(str(package))
        print('session started', 'with VNC on localhost:5901' if a.vnc else '')
    package = Path((work / 'package').read_text())
    launch = work / 'launch.sh'
    launch.write_text(f'''#!/bin/sh
# Runs PrePoMax-X in the Linux session ({NAME}); generated by X/Build/Linux/session.py
set --  "$@"
ENVS=""
for v in $(env | grep -o '^PREPOMAXX_[A-Z_]*'); do ENVS="$ENVS -e $v"; done
exec podman exec -w / $ENVS {NAME} timeout -s KILL "${{PREPOMAXX_SESSION_TIMEOUT:-470}}" "{package}/PrePoMax-X" "$@"
''')
    launch.chmod(0o755)
    print('launcher', launch)


if __name__ == '__main__':
    main()
